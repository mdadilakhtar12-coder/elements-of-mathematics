package com.coachsaas.app.util

import android.content.Context
import android.graphics.Color
import android.graphics.Paint
import android.graphics.Typeface
import android.graphics.pdf.PdfDocument
import com.coachsaas.app.AppConfig
import com.coachsaas.app.data.Fee
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.File

/** One fee payment as a small PDF receipt (A5), with the institute's name and the receipt number. */
object Receipt {
    suspend fun create(ctx: Context, f: Fee): File = withContext(Dispatchers.IO) {
        val w = 420
        val h = 595
        val doc = PdfDocument()
        val page = doc.startPage(PdfDocument.PageInfo.Builder(w, h, 1).create())
        val c = page.canvas

        val ink = Paint().apply { color = Color.parseColor("#1B1D2E"); textSize = 12f; isAntiAlias = true }
        val bold = Paint(ink).apply { typeface = Typeface.DEFAULT_BOLD }
        val grey = Paint(ink).apply { color = Color.parseColor("#6B7080"); textSize = 10.5f }
        val band = Paint().apply { color = Color.parseColor("#4338CA") }
        val white = Paint(ink).apply { color = Color.WHITE; typeface = Typeface.DEFAULT_BOLD; textSize = 17f }
        val line = Paint().apply { color = Color.parseColor("#E3E5F0"); strokeWidth = 1f }

        c.drawRect(0f, 0f, w.toFloat(), 78f, band)
        var name = AppConfig.APP_NAME.uppercase()
        while (white.measureText(name) > w - 60f && name.length > 4) name = name.dropLast(1)
        c.drawText(name, 30f, 36f, white)
        c.drawText("Fee Receipt", 30f, 60f, Paint(white).apply { textSize = 12f; typeface = Typeface.DEFAULT })

        var y = 110f
        if (f.receiptNo > 0) c.drawText("Receipt no: " + f.receiptNo, 30f, y, bold)
        val dateText = "Date: " + D.pretty(f.date)
        c.drawText(dateText, w - 30f - ink.measureText(dateText), y, ink)
        y += 18f
        c.drawLine(30f, y, w - 30f, y, line)
        y += 28f

        fun row(label: String, value: String) {
            if (value.isBlank()) return
            c.drawText(label, 30f, y, grey)
            var v = value
            while (ink.measureText(v) > w - 190f && v.length > 4) v = v.dropLast(1)
            c.drawText(v, 150f, y, ink)
            y += 24f
        }
        row("Received from", f.studentName)
        row("Fee for", D.monthLabel(f.month))
        row("Payment mode", f.mode)
        row("Note", f.note)
        row("Received by", f.receivedBy)

        y += 10f
        c.drawLine(30f, y, w - 30f, y, line)
        y += 40f
        c.drawText("Amount paid", 30f, y, grey)
        val amount = Paint(bold).apply { textSize = 26f; color = Color.parseColor("#16A34A") }
        val amt = D.rs(f.amount)
        c.drawText(amt, w - 30f - amount.measureText(amt), y + 6f, amount)

        c.drawText("This is a computer generated receipt.", 30f, h - 46f, grey)
        c.drawText("Generated by the " + AppConfig.APP_NAME + " app", 30f, h - 30f, grey)
        doc.finishPage(page)

        val dir = File(ctx.cacheDir, "reports")
        dir.mkdirs()
        val tag = if (f.receiptNo > 0) f.receiptNo.toString() else f.id.take(6)
        val out = File(dir, "Receipt-" + tag + "-" + f.studentName.replace(Regex("[^A-Za-z0-9]"), "_") + ".pdf")
        out.outputStream().use { doc.writeTo(it) }
        doc.close()
        out
    }
}
